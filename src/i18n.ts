const DICTS: Record<ToolboxLang, Record<string, string>> = { zh: ZH, en: EN }

/** Current UI language from the document (falls back to zh). */
export function currentLang(): ToolboxLang {
  if (typeof document !== 'undefined' && typeof document.documentElement?.lang === 'string') {
    return document.documentElement.lang.startsWith('zh') ? 'zh' : 'en'
  }
  return 'zh'
}

/** Look up one key; returns the key itself when untranslated. */
export function lookup(lang: ToolboxLang, key: string): string {
  return DICTS[lang][key] ?? DICTS.zh[key] ?? key
}
